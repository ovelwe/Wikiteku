export type PlatformErrorCode = keyof typeof platformErrors;
export class PlatformFailure extends Error {
  constructor(public code: PlatformErrorCode) {
    super(code);
  }
}
export function platformError(
  code: string | undefined,
  locale: Locale,
  fallback: PlatformErrorCode = "saveFailed",
) {
  const known =
    code && Object.hasOwn(platformErrors, code)
      ? (code as PlatformErrorCode)
      : fallback;
  return platformErrors[known][locale === "en" ? 1 : 0];
}
export function authError(
  code: string | undefined,
  locale: Locale,
  status?: number,
) {
  if (code === "EMAIL_NOT_VERIFIED")
    return locale === "en"
      ? "Verify your email before logging in. Check your inbox for a confirmation link."
      : "Перед входом подтвердите email. Проверьте письмо со ссылкой подтверждения.";
  if (code === "INVALID_SIGN_UP_INPUT")
    return locale === "en"
      ? "Check your name, username, email and password (10–128 characters)."
      : "Проверьте имя, логин, email и пароль (10–128 символов).";
  const key: PlatformErrorCode =
    status === 429
      ? "authLimit"
      : code === "INVALID_EMAIL_OR_PASSWORD"
        ? "credentials"
        : code === "USER_ALREADY_EXISTS_USE_ANOTHER_EMAIL" ||
            code === "USER_ALREADY_EXISTS"
          ? "accountExists"
          : code === "USERNAME_IS_ALREADY_TAKEN"
            ? "usernameTaken"
            : "authFailed";
  return platformError(key, locale);
}
